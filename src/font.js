const ADVANCE = 6;

export function measureText(text, scale = 1) {
  const str = String(text).toUpperCase();
  if (!str.length) return 0;
  return str.length * ADVANCE * scale - scale;
}

export function drawText(ctx, text, x, y, scale = 1, color = '#ffffff', align = 'left', shadow = null) {
  const str = String(text).toUpperCase();
  const width = measureText(str, scale);
  let sx = align === 'center' ? x - width / 2 : align === 'right' ? x - width : x;
  sx = Math.round(sx);
  const sy = Math.round(y);

  if (shadow) {
    paint(ctx, str, sx + scale, sy + scale, scale, shadow);
  }
  paint(ctx, str, sx, sy, scale, color);
}

function paint(ctx, str, sx, sy, scale, color) {
  ctx.fillStyle = color;
  let pen = sx;
  for (let i = 0; i < str.length; i++) {
    const rows = G[str[i]] || G[' '];
    for (let r = 0; r < 7; r++) {
      const row = rows[r];
      let run = -1;
      for (let c = 0; c <= 5; c++) {
        const on = c < 5 && row[c] === '1';
        if (on && run < 0) run = c;
        if (!on && run >= 0) {
          ctx.fillRect(pen + run * scale, sy + r * scale, (c - run) * scale, scale);
          run = -1;
        }
      }
    }
    pen += ADVANCE * scale;
  }
}

// Draw a line of text wrapped to a pixel width. Returns the vertical advance.
export function drawWrapped(ctx, text, x, y, maxWidth, scale, color, align = 'center', lineGap = 3) {
  const words = String(text).toUpperCase().split(/\s+/);
  const lines = [];
  let current = '';
  for (const word of words) {
    const next = current ? current + ' ' + word : word;
    if (measureText(next, scale) > maxWidth && current) {
      lines.push(current);
      current = word;
    } else {
      current = next;
    }
  }
  if (current) lines.push(current);
  const step = 7 * scale + lineGap;
  lines.forEach((line, i) => drawText(ctx, line, x, y + i * step, scale, color, align));
  return lines.length * step;
}
